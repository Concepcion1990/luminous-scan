/**
 * T35 — the labels PDFs draw a REAL barcode (owner catch, Nov 18,
 * 2026, during her final Essentials retest).
 *
 * She walked Scan → Print shelf tag → Print Center → Shelf label →
 * Labels PDF for a Deck of Cards (code 2657872040047, $2.50) and the
 * downloaded label carried NO barcode at all — name, price, SKU and
 * the code as big plain text. The Print Center itself promises the
 * shelf label is "Name, price and barcode"; a shelf label a scanner
 * cannot scan is useless.
 *
 * Diagnosis: the browser-print templates (LabelCard) and the ESC/POS
 * path always drew real bars, but BOTH PDF builders — the client
 * src/lib/labelsPdf.js and its server mirror server/printPdf.js —
 * rendered the code as text only, by an old design note ("the server
 * has no barcode font"). jsPDF needs no font: the bars are plain
 * rectangles from the same encoders the SVG templates use
 * (src/lib/barcodeSym.js; server/barcodeSym.js is its mirror).
 *
 * The proof below is not eyeballing: each PDF is generated by the
 * real builders, rasterised with pdftoppm, and the barcode zone is
 * decoded with the same ZXing reader the app's scanner uses — the
 * decoded text must equal the code exactly. The storage-bin label
 * template is NOT touched by any of this (owner exemption, Nov 14).
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  MultiFormatReader,
  BarcodeFormat,
  DecodeHintType,
  BinaryBitmap,
  HybridBinarizer,
  RGBLuminanceSource,
} from '@zxing/library';
import { buildLabelsPdfBytes } from '../../src/lib/labelsPdf.js';
import { buildLabelsPdf } from '../../server/printPdf.js';
import { barcodeRects as clientRects } from '../../src/lib/barcodeSym.js';
import { barcodeRects as serverRects } from '../../server/barcodeSym.js';

const read = (file) => readFileSync(file, 'utf8');

test('both PDF builders draw the barcode from the shared encoders', () => {
  const client = read('src/lib/labelsPdf.js');
  assert.match(client, /import \{ barcodeRects \} from '\.\/barcodeSym\.js'/);
  assert.match(client, /drawLabelBarcode\(doc, code, x \+ labelW \/ 2, y \+ codeY - 12\)/);
  const server = read('server/printPdf.js');
  assert.match(server, /import \{ barcodeRects \} from '\.\/barcodeSym\.js'/);
  assert.match(server, /drawLabelBarcode\(doc, code, x \+ labelW \/ 2, y \+ codeY - 12\)/);
  // The honest-text fallback survives for codes with no barcode.
  assert.match(client, /code \|\| 'NO CODE'/);
  assert.match(server, /code \|\| labelsText\.noCode/);
  // The exempt storage-bin template and the SVG renderer are untouched
  // by this fix — the legacy variant pin still stands.
  const bin = read('src/components/print/LabelCard.jsx');
  assert.match(bin, /template === 'bin'/);
  assert.match(read('src/components/print/BarcodeSvg.jsx'), /variant === 'legacy'/);
});

test('the server encoder mirror matches src rect-for-rect', () => {
  const battery = [
    '2657872040047', // valid EAN-13 (her Deck of Cards)
    '611269818994', // valid UPC-A (her RedBull)
    '9791090636071', // valid EAN-13 (bookland)
    '123456789012', // 12 digits, UPC-A
    '123456789013', // 12 digits, bad check digit → Code 128
    '2657872040048', // 13 digits, bad check digit → Code 128
    'DECK-OF-CARDS', // SKU → Code 128
    'REDBULL-TEST-COPY',
    'SH-ABCD1234',
    'A',
    '',
    'café ☕', // outside Code 128 set B → unencodable on both copies
  ];
  for (const code of battery) {
    assert.deepEqual(serverRects(code), clientRects(code), `mirror drift on ${JSON.stringify(code)}`);
  }
});

test('a code with no barcode still builds an honest text label', () => {
  const clientPdf = Buffer.from(
    buildLabelsPdfBytes([{ name: 'Mystery', price: 1, sku: '' }], { businessName: 'Shop' }),
  ).toString('latin1');
  assert.match(clientPdf, /NO CODE/);
  const serverPdf = buildLabelsPdf([{ name: 'Mystery', price: 1, sku: '' }], {
    businessName: 'Shop',
    language: 'en',
  }).toString('latin1');
  assert.match(serverPdf, /NO CODE/);
});

// ---- Render-and-decode proof -------------------------------------------

const hasPdftoppm = (() => {
  try {
    execFileSync('which', ['pdftoppm'], { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
})();

function parsePgm(buf) {
  let i = 0;
  const tokens = [];
  while (tokens.length < 4) {
    while (i < buf.length && (buf[i] === 32 || buf[i] === 10 || buf[i] === 13 || buf[i] === 9)) i += 1;
    if (buf[i] === 35) {
      while (i < buf.length && buf[i] !== 10) i += 1;
      continue;
    }
    let j = i;
    while (j < buf.length && !(buf[j] === 32 || buf[j] === 10 || buf[j] === 13 || buf[j] === 9)) j += 1;
    tokens.push(buf.toString('ascii', i, j));
    i = j;
  }
  i += 1;
  const [magic, w, h] = tokens;
  assert.equal(magic, 'P5');
  return { width: Number(w), height: Number(h), data: buf.subarray(i) };
}

/** Rasterise page 1 and ZXing-decode the first label's barcode zone. */
function decodeFirstLabel(pdfBytes, lineCount) {
  const dir = mkdtempSync(join(tmpdir(), 'label-barcode-proof-'));
  const pdfPath = join(dir, 'labels.pdf');
  writeFileSync(pdfPath, pdfBytes);
  execFileSync('pdftoppm', ['-gray', '-r', '300', pdfPath, join(dir, 'page')]);
  const pgm = parsePgm(readFileSync(join(dir, 'page-1.pgm')));
  const S = 300 / 72;
  // First label sits at (40, 56)pt; codeY follows the builders' rule.
  const codeY = Math.max(84, 52 + Math.min(lineCount, 3) * 16);
  const crop = {
    x0: Math.round((40 + 8) * S),
    x1: Math.round((40 + 244) * S),
    y0: Math.round((56 + codeY - 20) * S),
    y1: Math.round((56 + codeY + 18) * S),
  };
  const cw = crop.x1 - crop.x0;
  const ch = crop.y1 - crop.y0;
  const rgb = new Int32Array(cw * ch);
  for (let y = 0; y < ch; y += 1) {
    for (let x = 0; x < cw; x += 1) {
      const g = pgm.data[(crop.y0 + y) * pgm.width + (crop.x0 + x)];
      rgb[y * cw + x] = (g << 16) | (g << 8) | g;
    }
  }
  const bitmap = new BinaryBitmap(new HybridBinarizer(new RGBLuminanceSource(rgb, cw, ch)));
  const hints = new Map();
  hints.set(DecodeHintType.POSSIBLE_FORMATS, [
    BarcodeFormat.EAN_13,
    BarcodeFormat.UPC_A,
    BarcodeFormat.CODE_128,
  ]);
  hints.set(DecodeHintType.TRY_HARDER, true);
  return new MultiFormatReader().decode(bitmap, hints).getText();
}

const CASES = [
  [
    'her Deck of Cards (EAN-13)',
    { name: 'Deck of Cards', price: 2.5, sku: 'DECK-OF-CARDS', upc: '2657872040047', barcode: '2657872040047' },
    '2657872040047',
  ],
  [
    'a 12-digit UPC-A',
    { name: 'RedBull Test', price: 3.99, sku: 'REDBULL-TEST', upc: '611269818994', barcode: '611269818994' },
    '611269818994',
  ],
  [
    'a Code 128 fallback (SKU only)',
    { name: 'Deck of Cards', price: 2.5, sku: 'DECK-OF-CARDS' },
    'DECK-OF-CARDS',
  ],
];

for (const [name, product, expected] of CASES) {
  test(`client Labels PDF barcode decodes: ${name}`, { skip: !hasPdftoppm }, () => {
    const bytes = buildLabelsPdfBytes([product], { businessName: 'My Business' });
    assert.equal(decodeFirstLabel(bytes, 2), expected);
  });
  test(`server labels PDF barcode decodes: ${name}`, { skip: !hasPdftoppm }, () => {
    const bytes = buildLabelsPdf([product], { businessName: 'My Business', language: 'en' });
    assert.equal(decodeFirstLabel(bytes, 2), expected);
  });
}
