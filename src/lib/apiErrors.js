/**
 * API error copy — the leftovers sweep (Nov 15, 2026).
 *
 * The server has always answered errors as { error: <stable code>,
 * message: <English text> } (server err() helpers + route handlers).
 * Until now the client showed the English text verbatim, so every
 * banner stayed English whatever language the app ran in. This
 * module is the client-side half of the fix:
 *
 *   1. API_ERROR_MESSAGE_KEYS maps every distinct static English
 *      message the server can send to a locale key (apiErrors.*),
 *      translated in all 52 locales. Exact match only — the English
 *      strings are frozen, so an exact match is a certain match.
 *   2. API_ERROR_PATTERNS covers the messages the server composes
 *      with values inside (counts, names, locations): each pattern
 *      extracts the values and re-renders the sentence from its
 *      locale key with the same values slotted back in.
 *   3. API_ERROR_CODE_KEYS covers the handful of responses that
 *      carry a code and no message at all (e.g. 401 not_signed_in),
 *      which used to surface as the raw code in the banner.
 *
 * Anything unmapped falls back to the server's English message —
 * never a raw code, never a blank. tests/t35 pins the whole map
 * against a fresh scan of server/*.js, so a new server message
 * cannot land silently: it fails the suite until it is keyed.
 */
