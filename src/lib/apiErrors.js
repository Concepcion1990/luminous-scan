/**
 * The banner text for one failed API response, in the reader's
 * language whenever the server's words are known to the map.
 * data is the parsed response body; status the HTTP status.
 * fallbackKey names the generic failure string for the surface
 * (apiLib.requestFailed for calls, apiLib.downloadFailed for
 * downloads) used when the body carries nothing readable at all.
 */
export function apiErrorMessage(data, status, fallbackKey = 'apiLib.requestFailed') {
  const body = data && typeof data === 'object' ? data : {};
  const message = [body.message, body.detail].find(
    (value) => typeof value === 'string' && value.trim(),
  );
  if (message) {
    const key = API_ERROR_MESSAGE_KEYS[message];
    if (key) return t(key);
    for (const entry of API_ERROR_PATTERNS) {
      const match = entry.pattern.exec(message);
      if (match) {
        const vars = {};
        entry.vars.forEach((name, index) => {
          vars[name] = match[index + 1];
        });
        return t(entry.key, vars);
      }
    }
    // A body whose "message" is just the code repeated (a server
    // shape that exists in helpers) resolves through the code map
    // instead of printing the code as if it were a sentence.
    if (body.error && message === body.error && API_ERROR_CODE_KEYS[body.error]) {
      return t(API_ERROR_CODE_KEYS[body.error]);
    }
    return message;
  }
  const code = typeof body.error === 'string' ? body.error : '';
  if (code && API_ERROR_CODE_KEYS[code]) return t(API_ERROR_CODE_KEYS[code]);
  // An error field that is itself a sentence (older response shape)
  // is readable text — show it rather than a generic failure.
  if (code && /\s/.test(code)) return code;
  return t(fallbackKey, { status: status ?? '' });
}
